import { readFileSync } from "node:fs";
import { unzipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { exportMarkerBytes } from "../../src/core/export/marker";
import { GENERATOR } from "../../src/core/generator";
import { packTileset } from "../../src/core/pack/packTileset";
import { MANIFEST_ENTRY } from "../../src/core/project/format";
import { serialize } from "../../src/core/project/serialize";
import { generateRuntime } from "../../src/core/runtime/generate";
import { tilemapFor } from "../../src/core/tilemap";
import { meadowProject } from "./te-049-support";

// TE-067: release 1.0.0. The package's version is 1.0.0, and every file the editor writes names
// `ngne-tilemap-editor 1.0.0` as its generator (SUITE §1): the project file's manifest, each
// exported tilemap, atlas and folder marker, and the header of the generated runtime.

const RELEASE = "ngne-tilemap-editor 1.0.0";

function packageJson(): { name: string; version: string } {
    return JSON.parse(readFileSync(new URL("../../package.json", import.meta.url), "utf8"));
}

function json(bytes: Uint8Array): { generator?: unknown } {
    return JSON.parse(new TextDecoder().decode(bytes));
}

describe("release 1.0.0 generator strings", () => {
    it("package.json and its lockfile are at version 1.0.0", () => {
        expect(packageJson()).toMatchObject({ name: "ngne-tilemap-editor", version: "1.0.0" });
        const lock = JSON.parse(
            readFileSync(new URL("../../package-lock.json", import.meta.url), "utf8"),
        );
        expect(lock.version).toBe("1.0.0");
        expect(lock.packages[""].version).toBe("1.0.0");
    });

    it("the generator follows package.json", () => {
        const { name, version } = packageJson();
        expect(GENERATOR).toBe(`${name} ${version}`);
        expect(GENERATOR).toBe(RELEASE);
    });

    it("the project file's manifest names it", () => {
        const entries = unzipSync(serialize(meadowProject()));
        expect(json(entries[MANIFEST_ENTRY]!).generator).toBe(RELEASE);
    });

    it("an exported tilemap names it", () => {
        const project = meadowProject();
        expect(
            json(new TextEncoder().encode(tilemapFor(project, project.maps[0]!))).generator,
        ).toBe(RELEASE);
    });

    it("an exported atlas and the folder marker name it", () => {
        const project = meadowProject();
        const packed = packTileset(project.tilesets[0]!);
        expect(packed.atlas.generator).toBe(RELEASE);
        expect(json(exportMarkerBytes(project)).generator).toBe(RELEASE);
    });

    it("the generated runtime's header names it", () => {
        const source = generateRuntime({ tilemaps: ["meadow"], tilesets: ["grass"], images: [] });
        expect(source.split("\n")[0]).toBe(
            `// Generated by ${RELEASE}. Reads ngne-tilemap versions 1..1. Do not edit.`,
        );
    });
});
