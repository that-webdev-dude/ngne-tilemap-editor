import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";
import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { GENERATOR } from "../../src/core/generator";
import { generateRuntime, importsModule, TABLES_MARKER } from "../../src/core/runtime/generate";
import type * as Runtime from "../../src/core/runtime/runtime";
import { FIXTURE_DIR, meadowAtlases, meadowJson } from "./te-050-support";

// TE-050: the generator of `ngne-tilemap.ts` (SPEC 11.1). The output is checked as text, type-
// checked under the strictest settings a game uses, and run against the meadow fixture.

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const TABLES = { tilemaps: ["meadow", "cave"], tilesets: ["grass"], images: ["sky-1"] };

describe("generateRuntime", () => {
    const source = generateRuntime(TABLES);

    it("starts with the header", () => {
        expect(source.split("\n")[0]).toBe(
            `// Generated by ${GENERATOR}. Reads ngne-tilemap versions 1..1. Do not edit.`,
        );
        expect(GENERATOR).toMatch(/^ngne-tilemap-editor \d+\.\d+\.\d+$/);
    });

    it("has no import, and is ASCII with LF line ends", () => {
        expect(source).not.toMatch(/^\s*import[\s{*"']/m);
        expect(source).not.toMatch(/\bimport\s*\(/);
        expect(source).not.toMatch(/^\s*export\s[^;]*\sfrom\s/m);
        expect(source).not.toMatch(/\brequire\s*\(/);
        expect([...source].filter((char) => char.charCodeAt(0) > 0x7f)).toEqual([]);
        expect(source).not.toContain("\r");
        expect(source.endsWith("\n")).toBe(true);
    });

    it("inlines the emitter and the runtime, without the placeholder tables", () => {
        const emit = readFileSync(resolve(ROOT, "src/core/runtime/emit.ts"), "utf8");
        const runtime = readFileSync(resolve(ROOT, "src/core/runtime/runtime.ts"), "utf8");
        expect(source).toContain(emit.trimEnd());
        // Without its import of the emitter, which is inlined above it.
        const body = runtime
            .slice(0, runtime.indexOf(TABLES_MARKER))
            .replace(/^import\s[^;]*?\sfrom\s+"\.\/emit(?:\.ts)?";\n/gm, "");
        expect(source).toContain(body.trimEnd());
        expect(source).not.toContain(TABLES_MARKER);
        expect(source.match(/^export const TILEMAP_URLS/gm)).toHaveLength(1);
        expect(source).toContain("export class QuadEmitter");
        expect(source).toContain("export function readTilemap(");
    });

    it("writes the tables and the name types, sorted", () => {
        expect(source).toContain('export type TilemapName = "cave" | "meadow";');
        expect(source).toContain('export type TilesetName = "grass";');
        expect(source).toContain(
            [
                "export const TILEMAP_URLS: Readonly<Record<TilemapName, string>> = {",
                '    "cave": new URL("./cave.tilemap.json", import.meta.url).href,',
                '    "meadow": new URL("./meadow.tilemap.json", import.meta.url).href,',
                "};",
            ].join("\n"),
        );
        expect(source).toContain(
            [
                "export const ATLAS_URLS: Readonly<Record<TilesetName, AtlasUrls>> = {",
                '    "grass": {',
                '        json: new URL("./grass.atlas.json", import.meta.url).href,',
                '        png: new URL("./grass.png", import.meta.url).href,',
                "    },",
                "};",
            ].join("\n"),
        );
        expect(source).toContain(
            [
                "export const IMAGE_URLS: Readonly<Record<string, string>> = {",
                '    "sky-1": new URL("./sky-1.png", import.meta.url).href,',
                "};",
            ].join("\n"),
        );
    });

    it("gives the same bytes for the same tables, in any order", () => {
        const shuffled = {
            tilemaps: ["cave", "meadow"],
            tilesets: ["grass"],
            images: ["sky-1"],
        };
        expect(generateRuntime(shuffled)).toBe(source);
        expect(generateRuntime(TABLES)).toBe(source);
        expect(generateRuntime({ ...TABLES, images: [] })).not.toBe(source);
    });

    it("writes empty tables as never and {}", () => {
        const empty = generateRuntime({ tilemaps: [], tilesets: [], images: [] });
        expect(empty).toContain("export type TilemapName = never;");
        expect(empty).toContain("export type TilesetName = never;");
        expect(empty).toContain(
            "export const TILEMAP_URLS: Readonly<Record<TilemapName, string>> = {};",
        );
        expect(empty).toContain("export const IMAGE_URLS: Readonly<Record<string, string>> = {};");
    });

    it("refuses a name that is no slug or is repeated", () => {
        expect(() => generateRuntime({ ...TABLES, tilemaps: ["Meadow"] })).toThrow(/no slug/);
        expect(() => generateRuntime({ ...TABLES, tilemaps: ['a"b'] })).toThrow(/no slug/);
        expect(() => generateRuntime({ ...TABLES, tilesets: ["ngne-tilemap"] })).toThrow(/no slug/);
        expect(() => generateRuntime({ ...TABLES, images: ["sky", "sky"] })).toThrow(/repeated/);
    });
});

describe("the generated module", () => {
    let folder = "";

    beforeAll(() => {
        folder = mkdtempSync(join(tmpdir(), "te-050-"));
    });

    afterAll(() => {
        rmSync(folder, { recursive: true, force: true });
    });

    it("type-checks alone under strict game settings", () => {
        const file = join(folder, "ngne-tilemap.ts");
        writeFileSync(file, generateRuntime(TABLES));
        const empty = join(folder, "empty.ts");
        writeFileSync(empty, generateRuntime({ tilemaps: [], tilesets: [], images: [] }));
        const program = ts.createProgram([file, empty], {
            target: ts.ScriptTarget.ES2022,
            lib: ["lib.es2022.d.ts", "lib.dom.d.ts"],
            module: ts.ModuleKind.ESNext,
            moduleResolution: ts.ModuleResolutionKind.Bundler,
            types: [],
            strict: true,
            exactOptionalPropertyTypes: true,
            noUnusedLocals: true,
            noUnusedParameters: true,
            noImplicitOverride: true,
            noFallthroughCasesInSwitch: true,
            verbatimModuleSyntax: true,
            isolatedModules: true,
            noEmit: true,
        });
        const messages = ts
            .getPreEmitDiagnostics(program)
            .map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"));
        expect(messages).toEqual([]);
    }, 60_000);

    /** The generated module, compiled to JavaScript into the folder and imported from there. */
    async function load(): Promise<typeof Runtime> {
        const output = ts.transpileModule(generateRuntime(TABLES), {
            compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
        });
        const file = join(folder, "ngne-tilemap.mjs");
        writeFileSync(file, output.outputText);
        return (await import(/* @vite-ignore */ pathToFileURL(file).href)) as typeof Runtime;
    }

    /** A `fetch` that serves the fixture folder's files by name, and records the calls. */
    function fixtureFetch(override: (name: string) => Response | undefined = () => undefined) {
        return vi.fn((url: string, init?: { signal?: AbortSignal }) => {
            init?.signal?.throwIfAborted();
            const name = basename(new URL(url).pathname);
            const response = override(name);
            if (response !== undefined) return Promise.resolve(response);
            try {
                return Promise.resolve(new Response(readFileSync(join(FIXTURE_DIR, name))));
            } catch {
                return Promise.resolve(new Response("", { status: 404 }));
            }
        });
    }

    it("loads a tilemap and its atlases through its tables", async () => {
        const runtime = await load();
        const fetch = fixtureFetch();
        vi.stubGlobal("fetch", fetch);
        try {
            const tilemap = await runtime.loadTilemap("meadow");
            expect(tilemap).toEqual(runtime.readTilemap(meadowJson(), meadowAtlases()));
            expect(fetch.mock.calls.map(([url]) => url)).toEqual([
                new URL("meadow.tilemap.json", pathToFileURL(join(folder, "x"))).href,
                new URL("grass.atlas.json", pathToFileURL(join(folder, "x"))).href,
            ]);
            const assets = runtime.assetsFor(tilemap, (id, url) => ({ id, url }));
            expect(assets).toEqual([
                {
                    id: "ngne-tilemap:meadow-game/grass",
                    url: new URL("grass.png", pathToFileURL(join(folder, "x"))).href,
                },
            ]);
            expect(
                runtime.collisionRects(tilemap, tilemap.layers[0] as Runtime.TileLayerData),
            ).toEqual([{ x: 0, y: 32, width: 64, height: 16 }]);
        } finally {
            vi.unstubAllGlobals();
        }
    });

    it("passes the abort signal to every request", async () => {
        const runtime = await load();
        const fetch = fixtureFetch();
        vi.stubGlobal("fetch", fetch);
        try {
            const controller = new AbortController();
            await runtime.loadTilemap("meadow", controller.signal);
            expect(fetch.mock.calls.map(([, init]) => init?.signal)).toEqual([
                controller.signal,
                controller.signal,
            ]);
            controller.abort();
            await expect(runtime.loadTilemap("meadow", controller.signal)).rejects.toMatchObject({
                name: "AbortError",
            });
        } finally {
            vi.unstubAllGlobals();
        }
    });

    it("refuses a tilemap file over MAX_TILEMAP_BYTES before parsing it", async () => {
        const runtime = await load();
        const big = runtime.MAX_TILEMAP_BYTES + 1;
        const declared = vi.fn(() => Promise.resolve(""));
        vi.stubGlobal(
            "fetch",
            fixtureFetch((name) =>
                name === "meadow.tilemap.json"
                    ? ({
                          ok: true,
                          status: 200,
                          headers: new Headers({ "content-length": String(big) }),
                          text: declared,
                      } as unknown as Response)
                    : undefined,
            ),
        );
        try {
            await expect(runtime.loadTilemap("meadow")).rejects.toMatchObject({
                name: "TilemapError",
                code: "limit",
            });
            expect(declared).not.toHaveBeenCalled();
        } finally {
            vi.unstubAllGlobals();
        }
        vi.stubGlobal(
            "fetch",
            fixtureFetch((name) =>
                name === "meadow.tilemap.json" ? new Response(new Uint8Array(big)) : undefined,
            ),
        );
        try {
            await expect(runtime.loadTilemap("meadow")).rejects.toMatchObject({ code: "limit" });
        } finally {
            vi.unstubAllGlobals();
        }
        // Fewer UTF-16 code units than the limit, more UTF-8 bytes: 3 per euro sign.
        const euros = "€".repeat(Math.floor(runtime.MAX_TILEMAP_BYTES / 3) + 1);
        vi.stubGlobal(
            "fetch",
            fixtureFetch((name) =>
                name === "meadow.tilemap.json" ? new Response(euros) : undefined,
            ),
        );
        try {
            await expect(runtime.loadTilemap("meadow")).rejects.toMatchObject({ code: "limit" });
        } finally {
            vi.unstubAllGlobals();
        }
    }, 60_000);

    it("reports a file that is no tilemap, a missing file and an unknown name", async () => {
        const runtime = await load();
        vi.stubGlobal(
            "fetch",
            fixtureFetch((name) =>
                name === "meadow.tilemap.json" ? new Response("{") : undefined,
            ),
        );
        try {
            await expect(runtime.loadTilemap("meadow")).rejects.toMatchObject({
                name: "TilemapError",
                code: "format",
            });
            // The fixture folder has no cave.tilemap.json.
            await expect(runtime.loadTilemap("cave")).rejects.toThrow(/HTTP status 404/);
            await expect(runtime.loadTilemap("forest" as "cave")).rejects.toThrow(
                /no tilemap named "forest"/,
            );
        } finally {
            vi.unstubAllGlobals();
        }
        vi.stubGlobal(
            "fetch",
            fixtureFetch((name) =>
                name === "grass.atlas.json" ? new Response("not json") : undefined,
            ),
        );
        try {
            await expect(runtime.loadTilemap("meadow")).rejects.toMatchObject({ code: "atlas" });
        } finally {
            vi.unstubAllGlobals();
        }
    });
});

describe("importsModule", () => {
    it("finds an import or a re-export at the start of a line", () => {
        expect(importsModule('import { a } from "./a";\n')).toBe(true);
        expect(importsModule('  import * as a from "./a";\n')).toBe(true);
        expect(importsModule('\timport "./a";\n')).toBe(true);
        expect(importsModule("import{a}from'./a';\n")).toBe(true);
        expect(importsModule('export { a } from "./a";\n')).toBe(true);
        expect(importsModule('export * from "./a";\n')).toBe(true);
        expect(importsModule('export {\n    a,\n    b,\n} from "./a";\n')).toBe(true);
        expect(importsModule('const x = 1;\n    export type { A } from "./a";\n')).toBe(true);
    });

    it("finds none in code that only exports its own names", () => {
        expect(importsModule("export const a = 1;\nexport function f() {}\n")).toBe(false);
        expect(importsModule("const importer = 1;\nconst x = importer;\n")).toBe(false);
        expect(importsModule("export const a = 1; const from = 2;\n")).toBe(false);
        expect(importsModule("// import a from b\n")).toBe(false);
        expect(importsModule("const a = `\nexport` + 1;\nconst b = 2;\n")).toBe(false);
    });

    it("takes time linear in the code, on many lines that start a statement", () => {
        expect(importsModule("export a\n".repeat(200_000))).toBe(false);
        expect(importsModule(`${" ".repeat(200_000)}x\n`)).toBe(false);
        expect(importsModule(`${"\n".repeat(200_000)}x`)).toBe(false);
    });
});
